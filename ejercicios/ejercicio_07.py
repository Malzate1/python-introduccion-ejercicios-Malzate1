# Ejercicio 07: Verificador de Edad.

# Descripción: El ejercicio tiene como funcionalidad verificar según el rango de edad si es mayor de edad o no, con la ayuda de ciclos y datos booleanos.

# 1. Define la variable de captura. Acá es clave el "input".

edad = int (input("Cuál es su edad? :"))

# 2. Define el ciclo y sus condicionales con la ayuda de "if".

if edad >= 18:
    print("Eres mayor de edad.")

else:
    print("Eres menor de edad.")

